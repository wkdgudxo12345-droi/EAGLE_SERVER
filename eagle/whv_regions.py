from __future__ import annotations


def _expand(items: tuple[int | tuple[int, int], ...]) -> frozenset[int]:
    values: set[int] = set()
    for item in items:
        if isinstance(item, tuple):
            values.update(range(item[0], item[1] + 1))
        else:
            values.add(item)
    return frozenset(values)


